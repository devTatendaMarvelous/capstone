def nullable_feature_columns() -> list[str]:
    """Feature columns the generator is allowed to blank."""
    return [
        name
        for name, spec in COLUMN_SPECS.items()
        if spec["dtype"] in {"float", "int"} and spec.get("nullable", False)
    ]


def units_table() -> pd.DataFrame:
    """One row per observation column, for notebooks and data dictionaries."""
    rows = []
    for name in OBSERVATION_COLUMNS:
        spec = COLUMN_SPECS[name]
        rows.append(
            {
                "column": name,
                "dtype": spec["dtype"],
                "nullable": spec["nullable"],
                "unit": spec["unit"],
                "description": spec["description"],
                "plausible_min": spec.get("plausible_min"),
                "plausible_max": spec.get("plausible_max"),
            }
        )
    return pd.DataFrame(rows)


def coerce_observation_frame(df: pd.DataFrame) -> pd.DataFrame:
    """Return a frame restricted to the observation schema, with dtypes applied.

    Raises
    ------
    ValueError
        If a required column is absent. Extra columns are dropped.
    """
    missing = [column for column in OBSERVATION_COLUMNS if column not in df.columns]
    if missing:
        raise ValueError(f"Observation file is missing columns: {missing}")

    out = df.loc[:, OBSERVATION_COLUMNS].copy()
    for name, spec in COLUMN_SPECS.items():
        if spec["dtype"] == "float":
            out[name] = pd.to_numeric(out[name], errors="coerce")
        elif spec["dtype"] == "int":
            numeric = pd.to_numeric(out[name], errors="coerce")
            if spec["nullable"]:
                out[name] = numeric.round().astype("Int64")
            else:
                if numeric.isna().any():
                    raise ValueError(f"Column {name} contains missing values.")
                out[name] = numeric.round().astype("int64")
        else:
            out[name] = out[name].astype("string")
    return out
